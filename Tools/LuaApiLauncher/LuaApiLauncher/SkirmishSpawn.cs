using System.IO;
using System.Text;

namespace LuaApiLauncher;

/// <summary>
/// Writes the CnCNet spawner files for a skirmish match. spawn.ini carries the
/// player list and game options (including the per-AI difficulty from
/// [HouseHandicaps]); spawnmap.ini is the map the spawner loads. The match is
/// then started with gamemd-spawn.exe -SPAWN, exactly like the CnCNet client.
/// </summary>
public static class SkirmishSpawn
{
    public static string SpawnIniPath => Path.Combine(LauncherCore.Root, "spawn.ini");
    public static string SpawnMapPath => Path.Combine(LauncherCore.Root, "spawnmap.ini");

    /// <summary>
    /// The spawner needs an INI map it can read from disk. Packed maps
    /// (.mmx/.yro) are MIX archives, so they cannot be copied to spawnmap.ini.
    /// </summary>
    public static bool SupportsMap(MapEntry? map)
    {
        if (map == null || string.IsNullOrWhiteSpace(map.FilePath) || !File.Exists(map.FilePath))
            return false;
        var ext = Path.GetExtension(map.FilePath);
        return ext.Equals(".map", StringComparison.OrdinalIgnoreCase)
               || ext.Equals(".yrm", StringComparison.OrdinalIgnoreCase);
    }

    public static void Write(SkirmishConfig cfg, MapEntry map)
    {
        LauncherCore.EnsureSkirmishDefaults(cfg);

        var human = cfg.Players.FirstOrDefault(p => p.IsHuman) ?? cfg.Players[0];
        var ais = cfg.Players.Where(p => !ReferenceEquals(p, human)).ToList();
        if (ais.Count == 0)
            throw new UserFacingException(L10n.T("Добавьте хотя бы один ИИ-слот."));

        var factions = LauncherCore.SkirmishFactions();
        var colorCount = Math.Max(1, LauncherCore.SkirmishColors().Count);
        var rng = new Random();
        var (gameMode, uiGameMode) = ResolveGameMode(cfg.SelectedMode);

        // The spawner identifies a house by its country index and two houses may
        // not share one, so a faction that is already taken goes to a free one.
        var taken = new HashSet<int>();
        var humanCountry = ResolveCountry(human.Country, factions, rng, taken);
        var humanColor = Math.Clamp(human.Color, 0, colorCount - 1);

        var aiCountries = ais.Select(a => ResolveCountry(a.Country, factions, rng, taken)).ToList();
        var aiColors = ais.Select(a => Math.Clamp(a.Color, 0, colorCount - 1)).ToList();

        WriteSpawnMap(map, cfg.Options);
        WriteSpawnIni(cfg, map, human, ais, humanCountry, humanColor, aiCountries, aiColors, gameMode, uiGameMode);
    }

    /// <summary>
    /// Country index for one slot: the faction the slot picked (its first
    /// house), a random faction for "Random", and a free one when the faction
    /// is already taken by another house.
    /// </summary>
    private static int ResolveCountry(int requested, List<FactionOption> factions, Random rng, HashSet<int> taken)
    {
        if (factions.Count == 0) return Math.Max(0, requested);
        var picked = factions.FindIndex(f => f.PrimaryIndex == requested);
        if (picked < 0) picked = rng.Next(0, factions.Count);
        var primary = factions[picked].PrimaryIndex;
        if (taken.Contains(primary))
        {
            var free = factions.Where(f => !taken.Contains(f.PrimaryIndex)).ToList();
            if (free.Count > 0) primary = free[rng.Next(0, free.Count)].PrimaryIndex;
        }
        taken.Add(primary);
        return primary;
    }

    private static (int GameMode, string UiName) ResolveGameMode(string? selectedMode)
    {
        var mode = selectedMode ?? "";
        var ini = IniFile.Load(Path.Combine(LauncherCore.Root, "INI", "MPMaps.ini"));
        var forcedSection = ini.Get(mode, "ForcedSpawnIniOptions");
        if (!string.IsNullOrWhiteSpace(forcedSection))
        {
            var value = ini.Get(forcedSection, "GameMode");
            if (int.TryParse(value, out var gameMode)) return (gameMode, mode);
        }
        return (1, "Battle");
    }

    private static void WriteSpawnIni(
        SkirmishConfig cfg, MapEntry map, SkirmishPlayer human, List<SkirmishPlayer> ais,
        int humanCountry, int humanColor, List<int> aiCountries, List<int> aiColors,
        int gameMode, string uiGameMode)
    {
        var o = cfg.Options;
        var sb = new StringBuilder();
        sb.AppendLine("; Generated by Yuri's Echo launcher for skirmish launch");
        sb.AppendLine("[Settings]");
        sb.AppendLine("Name=" + CleanValue(string.IsNullOrWhiteSpace(human.Name) ? "Player" : human.Name));
        sb.AppendLine("Scenario=spawnmap.ini");
        sb.AppendLine("UIGameMode=" + CleanValue(uiGameMode));
        sb.AppendLine("UIMapName=" + CampaignData.SanitizeUiName(
            string.IsNullOrWhiteSpace(map.DisplayName) ? map.Name : map.DisplayName));
        sb.AppendLine("PlayerCount=1");
        // Side carries the country index of the local player: the spawner
        // resolves it against the rules' [Countries] table, not a side list.
        sb.AppendLine("Side=" + humanCountry);
        sb.AppendLine("Color=" + humanColor);
        sb.AppendLine("AIPlayers=" + ais.Count);
        sb.AppendLine("Seed=" + Random.Shared.Next(1, int.MaxValue));
        sb.AppendLine("GameMode=" + gameMode);
        sb.AppendLine("Bases=Yes");
        sb.AppendLine("Credits=" + Math.Max(0, o.Credits));
        sb.AppendLine("UnitCount=" + Math.Max(0, o.UnitCount));
        sb.AppendLine("GameSpeed=" + Math.Clamp(o.GameSpeed, 1, 6));
        sb.AppendLine("ShortGame=" + YesNo(o.ShortGame));
        sb.AppendLine("BridgeDestroy=" + YesNo(o.BridgeDestroy));
        sb.AppendLine("BuildOffAlly=" + YesNo(o.BuildOffAlly));
        sb.AppendLine("MultiEngineer=" + YesNo(o.MultiEngineer));
        sb.AppendLine("MCVRedeploy=" + YesNo(o.MCVRedeploy));
        sb.AppendLine("AlliesAllowed=" + YesNo(o.AlliesAllowed));
        sb.AppendLine("Crates=" + YesNo(o.Crates));

        // The CnCNet client writes these last, so a mod's forced values win.
        // Superweapons are applied through the map code below, like CnCNet does.
        foreach (var (key, value) in CampaignData.ReadForcedSpawnIniOptions())
        {
            if (string.IsNullOrWhiteSpace(key)) continue;
            sb.AppendLine(key + "=" + value);
        }

        sb.AppendLine();
        sb.AppendLine("[HouseHandicaps]");
        for (var i = 0; i < ais.Count; i++)
            sb.AppendLine("Multi" + (i + 2) + "=" + Math.Clamp(2 - ais[i].AiLevel, 0, 2));

        sb.AppendLine();
        sb.AppendLine("[HouseCountries]");
        for (var i = 0; i < ais.Count; i++)
            sb.AppendLine("Multi" + (i + 2) + "=" + aiCountries[i]);

        sb.AppendLine();
        sb.AppendLine("[HouseColors]");
        for (var i = 0; i < ais.Count; i++)
            sb.AppendLine("Multi" + (i + 2) + "=" + aiColors[i]);

        sb.AppendLine();
        sb.AppendLine("[SpawnLocations]");
        if (human.Start is >= 1 and <= 8)
            sb.AppendLine("Multi1=" + (human.Start - 1));
        for (var i = 0; i < ais.Count; i++)
        {
            var start = ais[i].Start;
            if (start is >= 1 and <= 8)
                sb.AppendLine("Multi" + (i + 2) + "=" + (start - 1));
        }

        File.WriteAllText(SpawnIniPath, sb.ToString(), new UTF8Encoding(false));
    }

    /// <summary>
    /// spawnmap.ini starts as a copy of the selected map, then the selected map
    /// code options (auto repair, in-game allying, superweapons) are merged in,
    /// the same way the CnCNet client's lobby options are applied.
    /// </summary>
    private static void WriteSpawnMap(MapEntry map, SkirmishOptions options)
    {
        if (!SupportsMap(map))
            throw new UserFacingException(L10n.T(
                "Для этой карты нет распакованного .map/.yrm файла. Выберите карту из списка, у которой есть .map."));

        var ini = IniFile.Load(map.FilePath);

        if (options.AutoRepair)
            MergeMapCode(ini, "INI/Game Options/Auto Repair.ini");
        if (options.AlliesAllowed)
            MergeMapCode(ini, "INI/Game Options/Allies Allowed.ini");

        var superWeapons = options.SuperWeapons switch
        {
            1 => "Offensive.ini",
            2 => "Defensive.ini",
            3 => "Disabled.ini",
            _ => "All.ini"
        };
        MergeMapCode(ini, "INI/Game Options/SuperWeapons/" + superWeapons);

        ini.Save(SpawnMapPath);
    }

    private static void MergeMapCode(IniFile target, string relativePath)
    {
        var path = Path.Combine(LauncherCore.Root, relativePath);
        if (!File.Exists(path)) return;

        var source = IniFile.Load(path);
        foreach (var section in source.Sections().Distinct(StringComparer.OrdinalIgnoreCase))
            foreach (var (key, value) in source.Section(section))
                target.Set(section, key, value);
    }

    private static string YesNo(bool value) => value ? "Yes" : "No";

    private static string CleanValue(string value) =>
        value.Replace('\r', ' ').Replace('\n', ' ').Trim();
}
